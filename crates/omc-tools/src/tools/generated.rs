//! Telling files a tool or package manager writes from files people write, so
//! that `edit`, `write` and `ast_edit` keep their hands off the former unless
//! the model says the user asked for exactly that.
//!
//! A file counts as machine-written when its name is one generators and package
//! managers use, or when a comment near its top says so. Only comment lines are
//! read, in the comment syntax the file's extension calls for, so source that
//! merely mentions such a banner in a string, or a Markdown heading or bullet,
//! is not mistaken for it. A comment counts only when it reads as a banner:
//! `@generated`, "generated" with a warning not to edit, a sentence saying the
//! file was generated, or, in the first few lines, "generated by" a known
//! generator; a passing mention of something being auto-generated does not.

use std::io::Read as _;
use std::path::Path;

use crate::ToolError;

/// How many lines at the top of a file are searched for a banner.
const HEADER_LINES: usize = 30;

/// How many bytes at the top of a file are read to find its banner.
const HEADER_BYTES: u64 = 16 * 1024;

/// Longest banner line quoted as evidence, in characters.
const QUOTE_CHARS: usize = 120;

/// Exact file names, lowercased, of lockfiles that package managers write.
const LOCKFILES: &[&str] = &[
    "cargo.lock",
    "package-lock.json",
    "npm-shrinkwrap.json",
    "yarn.lock",
    "pnpm-lock.yaml",
    "bun.lock",
    "bun.lockb",
    "go.sum",
    "poetry.lock",
    "pipfile.lock",
    "uv.lock",
    "pdm.lock",
    "gemfile.lock",
    "composer.lock",
    "flake.lock",
    "pubspec.lock",
    "podfile.lock",
    "mix.lock",
    "packages.lock.json",
    "gradle.lockfile",
];

/// Endings of file names, lowercased, that code generators give their output.
const GENERATED_SUFFIXES: &[&str] = &[
    ".pb.go",
    ".pb.gw.go",
    ".pb.cc",
    ".pb.h",
    ".pb.c",
    ".pb.js",
    ".pb.ts",
    ".pb.swift",
    "_pb.js",
    "_pb.d.ts",
    "_pb2.py",
    "_pb2.pyi",
    "_pb2_grpc.py",
    ".g.dart",
    ".freezed.dart",
    ".pbenum.dart",
    ".pbgrpc.dart",
    ".designer.cs",
    ".g.cs",
    ".g.i.cs",
];

/// Starts of file names, lowercased, that code generators give their output.
const GENERATED_PREFIXES: &[&str] = &["zz_generated."];

/// How many lines at the top of a file are searched for a generator's
/// banner that carries no warning not to edit.
const GENERATOR_LINES: usize = 10;

/// Phrases, lowercased, that only a banner of generated code contains, found
/// anywhere in the first [`HEADER_LINES`] lines.
const BANNERS: &[&str] = &[
    "@generated",
    "<auto-generated",
    "this file was automatically generated",
    "this file is automatically generated",
    "this file was auto-generated",
    "this file is auto-generated",
    "this file was auto generated",
    "this file is auto generated",
    "this file was autogenerated",
    "this file is autogenerated",
    "this file was generated by",
    "this file is generated by",
    "this file has been generated",
    "this code was generated by",
    "this code is generated by",
];

/// Names, lowercased, of code generators whose banners say only that they
/// generated the file, counted when a comment in the first
/// [`GENERATOR_LINES`] lines says `generated` and names one.
const GENERATORS: &[&str] = &[
    "protocol buffer compiler",
    "protoc",
    "sqlc",
    "swagger code generator",
    "swagger-codegen",
    "openapi generator",
    "openapi-generator",
    "grpc",
    "flatbuffers compiler",
    "flatc",
    "thrift compiler",
];

/// Phrases, lowercased, that turn a comment mentioning generation into a banner.
const WARNINGS: &[&str] = &["do not edit", "do not modify", "don't edit", "dont edit"];

/// How comments are written in a kind of file.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
struct Syntax {
    /// What starts a comment that runs to the end of the line.
    lines: &'static [&'static str],
    /// What opens and closes a block comment.
    blocks: &'static [(&'static str, &'static str)],
}

/// Comments of C and the languages that borrow its syntax.
const C_LIKE: Syntax = Syntax {
    lines: &["//"],
    blocks: &[("/*", "*/")],
};

/// Comments of shells, Python, Ruby and configuration formats.
const HASH: Syntax = Syntax {
    lines: &["#"],
    blocks: &[],
};

/// Comments of Markdown, HTML, XML and plain text, which only `<!-- -->`
/// makes.
const MARKUP: Syntax = Syntax {
    lines: &[],
    blocks: &[("<!--", "-->")],
};

/// Comments of SQL, Lua, Haskell and Elm.
const DASHES: Syntax = Syntax {
    lines: &["--"],
    blocks: &[("{-", "-}")],
};

/// Comments of Lisps, assembly and INI files.
const SEMICOLON: Syntax = Syntax {
    lines: &[";"],
    blocks: &[],
};

/// Comments of TeX, Erlang and MATLAB.
const PERCENT: Syntax = Syntax {
    lines: &["%"],
    blocks: &[],
};

/// Comments of Visual Basic and batch files.
const BASIC: Syntax = Syntax {
    lines: &["'", "rem ", "::"],
    blocks: &[],
};

/// Comments of OCaml and F#.
const ML: Syntax = Syntax {
    lines: &["//"],
    blocks: &[("(*", "*)")],
};

/// Comments of PHP, which takes both `//` and `#`.
const PHP: Syntax = Syntax {
    lines: &["//", "#"],
    blocks: &[("/*", "*/")],
};

/// Comments of single-file components, which mix markup and script.
const COMPONENT: Syntax = Syntax {
    lines: &["//"],
    blocks: &[("/*", "*/"), ("<!--", "-->")],
};

/// Comments of files whose kind is not known: the common syntaxes that are
/// unlikely to start a line of anything else.
const UNKNOWN: Syntax = Syntax {
    lines: &["//", "#", "--"],
    blocks: &[("/*", "*/"), ("<!--", "-->")],
};

/// How comments are written in the file at `path`, judged by its name.
fn syntax(path: &Path) -> Syntax {
    let name = path
        .file_name()
        .map(|name| name.to_string_lossy().to_lowercase())
        .unwrap_or_default();
    if matches!(
        name.as_str(),
        "makefile"
            | "gnumakefile"
            | "dockerfile"
            | "containerfile"
            | "cmakelists.txt"
            | "gemfile"
            | "rakefile"
            | "justfile"
            | "build"
            | "workspace"
            | ".gitignore"
            | ".dockerignore"
            | ".env"
    ) {
        return HASH;
    }
    let extension = name.rsplit_once('.').map_or("", |(_, extension)| extension);
    match extension {
        "rs" | "go" | "c" | "h" | "cc" | "cpp" | "cxx" | "hh" | "hpp" | "hxx" | "m" | "mm"
        | "java" | "kt" | "kts" | "scala" | "groovy" | "gradle" | "js" | "jsx" | "mjs" | "cjs"
        | "ts" | "tsx" | "mts" | "cts" | "cs" | "swift" | "dart" | "proto" | "css" | "scss"
        | "less" | "zig" | "sol" | "fbs" | "thrift" | "json5" | "jsonc" | "v" | "d" => C_LIKE,
        "sh" | "bash" | "zsh" | "fish" | "ksh" | "py" | "pyi" | "pyx" | "rb" | "pl" | "pm"
        | "r" | "toml" | "yaml" | "yml" | "cmake" | "mk" | "nix" | "tf" | "hcl" | "ex" | "exs"
        | "cr" | "jl" | "ps1" | "psm1" | "conf" | "cfg" | "properties" | "graphql" | "gql"
        | "bzl" | "star" | "tcl" | "awk" | "sed" | "dockerfile" => HASH,
        "md" | "markdown" | "mdx" | "txt" | "text" | "rst" | "adoc" | "html" | "htm" | "xhtml"
        | "xml" | "xsd" | "xsl" | "svg" | "plist" | "csproj" | "props" | "targets" | "resx"
        | "xaml" => MARKUP,
        "sql" | "lua" | "hs" | "lhs" | "elm" | "purs" | "ada" | "adb" | "ads" => DASHES,
        "lisp" | "lsp" | "cl" | "el" | "clj" | "cljs" | "cljc" | "edn" | "scm" | "rkt" | "asm"
        | "s" | "ini" => SEMICOLON,
        "tex" | "sty" | "cls" | "erl" | "hrl" | "matlab" => PERCENT,
        "vb" | "vbs" | "bas" | "bat" | "cmd" => BASIC,
        "ml" | "mli" | "fs" | "fsi" | "fsx" => ML,
        "php" => PHP,
        "vue" | "svelte" | "astro" => COMPONENT,
        _ => UNKNOWN,
    }
}

/// Why the file at `path`, holding `text` (at least its first lines), looks
/// generated: its name or the banner comment line that says so. `None` when
/// nothing marks it as generated.
pub(crate) fn evidence(path: &Path, text: &str) -> Option<String> {
    by_name(path).or_else(|| by_banner(text, syntax(path)))
}

/// Refuses a change to the file at `path`, shown as `shown` and holding `text`,
/// when it looks generated, unless `allowed` says the user asked for it.
///
/// `flag` names the argument that allows it, as the model would set it.
///
/// # Errors
///
/// Returns [`ToolError::Failed`] saying the file is generated, why, and what to
/// change instead.
pub(crate) fn refuse(
    path: &Path,
    shown: &str,
    text: &str,
    allowed: bool,
    flag: &str,
) -> Result<(), ToolError> {
    if allowed {
        return Ok(());
    }
    match evidence(path, text) {
        Some(why) => Err(ToolError::Failed(message(shown, &why, flag))),
        None => Ok(()),
    }
}

/// Refuses a change to the existing file at `path`, shown as `shown`, as
/// [`refuse`] does, reading only the top of the file.
///
/// # Errors
///
/// See [`refuse`]. A file that cannot be read is not refused; the change
/// reports that itself.
pub(crate) fn refuse_existing(
    path: &Path,
    shown: &str,
    allowed: bool,
    flag: &str,
) -> Result<(), ToolError> {
    if allowed || !path.is_file() {
        return Ok(());
    }
    refuse(path, shown, &head(path), allowed, flag)
}

/// The refusal for the file `shown`, generated as `why` says, telling the
/// model to set `flag` only when the user asked to change this file itself.
pub(crate) fn message(shown: &str, why: &str, flag: &str) -> String {
    format!(
        "{shown} is a generated file ({why}); a change made by hand is lost the next time it \
         is generated. Change the source it is generated from or the generator's \
         configuration and regenerate it instead; for a lockfile, change the manifest and let \
         the package manager update the lockfile. Only if the user explicitly asked you to \
         change this file itself, call again with {flag}."
    )
}

/// The first [`HEADER_BYTES`] bytes of the file at `path`, as text; empty
/// when it cannot be read.
fn head(path: &Path) -> String {
    let mut bytes = Vec::new();
    let _ =
        std::fs::File::open(path).and_then(|file| file.take(HEADER_BYTES).read_to_end(&mut bytes));
    String::from_utf8_lossy(&bytes).into_owned()
}

/// Why the name of `path` marks it as generated: a lockfile or a name
/// generators use.
fn by_name(path: &Path) -> Option<String> {
    let name = path.file_name()?.to_string_lossy();
    let lower = name.to_lowercase();
    if LOCKFILES.contains(&lower.as_str()) {
        return Some(format!(
            "{name} is a lockfile written by its package manager"
        ));
    }
    if let Some(suffix) = GENERATED_SUFFIXES
        .iter()
        .find(|suffix| lower.ends_with(*suffix))
    {
        return Some(format!(
            "its name matches *{suffix}, which code generators write"
        ));
    }
    GENERATED_PREFIXES
        .iter()
        .find(|prefix| lower.starts_with(*prefix))
        .map(|prefix| format!("its name matches {prefix}*, which code generators write"))
}

/// The comment line among the first [`HEADER_LINES`] lines of `text`, whose
/// comments are written as `syntax` says, that says the file is generated,
/// quoted with its line number.
fn by_banner(text: &str, syntax: Syntax) -> Option<String> {
    let text = text.strip_prefix('\u{feff}').unwrap_or(text);
    let mut block: Option<&str> = None;
    for (index, line) in text.lines().take(HEADER_LINES).enumerate() {
        let trimmed = line.trim();
        let comment = match block {
            Some(close) => {
                if trimmed.contains(close) {
                    block = None;
                }
                true
            }
            None => {
                block = opens_block(trimmed, syntax);
                block.is_some() || is_comment(trimmed, syntax)
            }
        };
        if comment && is_banner(&trimmed.to_lowercase(), index < GENERATOR_LINES) {
            return Some(format!("line {}: {}", index + 1, quote(trimmed)));
        }
    }
    None
}

/// Whether `line`, trimmed, is a whole comment in `syntax`: a line comment,
/// or a block comment opened and closed on it.
fn is_comment(line: &str, syntax: Syntax) -> bool {
    syntax.lines.iter().any(|start| line.starts_with(start))
        || syntax.blocks.iter().any(|(open, _)| line.starts_with(open))
}

/// The text that closes the block comment `line`, trimmed, opens in `syntax`
/// and leaves open, if it does.
fn opens_block(line: &str, syntax: Syntax) -> Option<&'static str> {
    syntax
        .blocks
        .iter()
        .find(|(open, close)| line.starts_with(open) && !line[open.len()..].contains(close))
        .map(|(_, close)| *close)
}

/// Whether the lowercased comment `line` is a banner of generated code: a
/// phrase only banners use, the word generated next to a warning not to
/// edit, or, when `near_top` says the line is among the first
/// [`GENERATOR_LINES`], "generated by" followed by the name of a generator.
fn is_banner(line: &str, near_top: bool) -> bool {
    BANNERS.iter().any(|phrase| line.contains(phrase))
        || (line.contains("generated") && WARNINGS.iter().any(|warning| line.contains(warning)))
        || (near_top && by_generator(line))
}

/// Whether the lowercased `line` says "generated by", or "autogenerated
/// by", but not "regenerated by", followed by the name of a generator.
fn by_generator(line: &str) -> bool {
    line.match_indices("generated by").any(|(at, phrase)| {
        let before = &line[..at];
        let word_start = before
            .chars()
            .next_back()
            .is_none_or(|c| !c.is_alphabetic())
            || before.ends_with("auto");
        let after = &line[at + phrase.len()..];
        word_start && GENERATORS.iter().any(|name| after.contains(name))
    })
}

/// `line` in quotes, cut to [`QUOTE_CHARS`] characters.
fn quote(line: &str) -> String {
    match line.char_indices().nth(QUOTE_CHARS) {
        Some((end, _)) => format!("\"{}…\"", &line[..end]),
        None => format!("\"{line}\""),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The evidence for a file named `name` holding `text`.
    fn why(name: &str, text: &str) -> Option<String> {
        evidence(Path::new(name), text)
    }

    /// Banners of the common generators are found in comments near the top.
    #[test]
    fn finds_banners() {
        for (name, text) in [
            (
                "a.go",
                "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage a\n",
            ),
            (
                "b.go",
                "package b\n\n// Code generated by stringer; DO NOT EDIT.\n",
            ),
            (
                "c.py",
                "# -*- coding: utf-8 -*-\n# Generated by the protocol buffer compiler.  DO NOT EDIT!\n",
            ),
            ("d.rs", "// This file is @generated by prost-build.\n"),
            (
                "e.cs",
                "//------\n// <auto-generated>\n//     This code was generated by a tool.\n// </auto-generated>\n",
            ),
            (
                "f.ts",
                "/**\n * NOTE: This class is auto generated by OpenAPI Generator.\n */\n",
            ),
            (
                "g.java",
                "/**\n Autogenerated by Thrift Compiler (0.19.0)\n */\n",
            ),
            (
                "h.h",
                "// automatically generated by the FlatBuffers compiler, do not modify\n",
            ),
            ("i.sql", "-- Code generated by sqlc. DO NOT EDIT.\n"),
            (
                "j.html",
                "<!--\n  This file was automatically generated.\n-->\n",
            ),
        ] {
            assert!(why(name, text).is_some(), "{name}");
        }
        let quoted = why("a.go", "// Code generated by mockgen. DO NOT EDIT.\n").unwrap();
        assert_eq!(
            quoted,
            "line 1: \"// Code generated by mockgen. DO NOT EDIT.\""
        );
    }

    /// Lockfiles and the names generators use are known by name alone.
    #[test]
    fn knows_names() {
        for name in [
            "Cargo.lock",
            "web/package-lock.json",
            "yarn.lock",
            "pnpm-lock.yaml",
            "go.sum",
            "api/v1/service.pb.go",
            "proto/msg_pb2.py",
            "lib/model.g.dart",
            "Form1.Designer.cs",
            "zz_generated.deepcopy.go",
        ] {
            assert!(why(name, "").is_some(), "{name}");
        }
        assert!(why("Cargo.lock", "").unwrap().contains("lockfile"));
        assert!(why("x.pb.go", "").unwrap().contains("*.pb.go"));
    }

    /// Hand-written files are left alone: banners only count in comments near
    /// the top, and a mention of generation without a warning is not one.
    #[test]
    fn leaves_hand_written_files_alone() {
        assert_eq!(why("main.rs", "fn main() {}\n"), None);
        assert_eq!(
            why(
                "guard.rs",
                "const BANNER: &str = \"// Code generated DO NOT EDIT\";\n"
            ),
            None
        );
        assert_eq!(why("lib.rs", "// Parses the generated tokens.\n"), None);
        let late = format!(
            "{}// Code generated by x. DO NOT EDIT.\n",
            "fn f() {}\n".repeat(40)
        );
        assert_eq!(why("late.go", &late), None);
        assert_eq!(why("Cargo.toml", "[package]\n"), None);
    }

    /// Markdown headings and bullets, and doc comments that mention
    /// generation, are not banners.
    #[test]
    fn ignores_mentions_of_generation() {
        let readme = "# API client\n\n## Regenerating with openapi-generator\n\n\
                      * Code is generated by protoc from proto/; do not edit by hand\n\
                      ; auto-generated by the build\n% generated by swagger-codegen\n";
        assert_eq!(why("README.md", readme), None);
        assert_eq!(
            why(
                "model.rs",
                "/// The row's id, auto-generated by the database.\npub struct Id(u64);\n"
            ),
            None
        );
        assert_eq!(
            why(
                "build.py",
                "# Regenerated by protoc when the schema changes.\n"
            ),
            None
        );
        let late = format!(
            "{}// Autogenerated by Thrift Compiler\n",
            "// notes\n".repeat(12)
        );
        assert_eq!(why("late.java", &late), None);
        assert_eq!(why("ptr.c", "*p = 0; // generated by flatc\n"), None);
        assert!(
            why(
                "README.md",
                "<!-- This file was automatically generated. -->\n"
            )
            .is_some()
        );
        assert!(
            why(
                "gen.py",
                "# Generated by the gRPC Python protocol compiler plugin.\n"
            )
            .is_some()
        );
    }

    /// The refusal names the evidence and the escape, and the escape lets the change through.
    #[test]
    fn refuses_unless_allowed() {
        let path = Path::new("x.pb.go");
        let refused = refuse(path, "x.pb.go", "", false, "generated: true").unwrap_err();
        let text = refused.to_string();
        assert!(text.contains("x.pb.go is a generated file"), "{text}");
        assert!(text.contains("*.pb.go"), "{text}");
        assert!(text.contains("generated: true"), "{text}");
        assert!(refuse(path, "x.pb.go", "", true, "generated: true").is_ok());
        assert!(
            refuse(
                Path::new("x.go"),
                "x.go",
                "package x\n",
                false,
                "generated: true"
            )
            .is_ok()
        );
    }
}
