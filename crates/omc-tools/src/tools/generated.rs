//! Telling files a tool or package manager writes from files people write, so
//! that `edit`, `write` and `ast_edit` keep their hands off the former unless
//! the model says the user asked for exactly that.
//!
//! A file counts as machine-written when its name is one generators and package
//! managers use, or when a comment near its top says so. Only comment lines are
//! read, so source that merely mentions such a banner in a string is not
//! mistaken for it.

use std::io::Read as _;
use std::path::Path;

use crate::ToolError;

/// How many lines at the top of a file are searched for a banner.
const HEADER_LINES: usize = 30;

/// How many bytes at the top of a file are read to find its banner.
const HEADER_BYTES: u64 = 16 * 1024;

/// Longest banner line quoted as evidence, in characters.
const QUOTE_CHARS: usize = 120;

/// Exact file names, lowercased, of lockfiles that package managers write.
const LOCKFILES: &[&str] = &[
    "cargo.lock",
    "package-lock.json",
    "npm-shrinkwrap.json",
    "yarn.lock",
    "pnpm-lock.yaml",
    "bun.lock",
    "bun.lockb",
    "go.sum",
    "poetry.lock",
    "pipfile.lock",
    "uv.lock",
    "pdm.lock",
    "gemfile.lock",
    "composer.lock",
    "flake.lock",
    "pubspec.lock",
    "podfile.lock",
    "mix.lock",
    "packages.lock.json",
    "gradle.lockfile",
];

/// Endings of file names, lowercased, that code generators give their output.
const GENERATED_SUFFIXES: &[&str] = &[
    ".pb.go",
    ".pb.gw.go",
    ".pb.cc",
    ".pb.h",
    ".pb.c",
    ".pb.js",
    ".pb.ts",
    ".pb.swift",
    "_pb.js",
    "_pb.d.ts",
    "_pb2.py",
    "_pb2.pyi",
    "_pb2_grpc.py",
    ".g.dart",
    ".freezed.dart",
    ".pbenum.dart",
    ".pbgrpc.dart",
    ".designer.cs",
    ".g.cs",
    ".g.i.cs",
];

/// Starts of file names, lowercased, that code generators give their output.
const GENERATED_PREFIXES: &[&str] = &["zz_generated."];

/// Phrases, lowercased, that only a banner of generated code contains.
const BANNERS: &[&str] = &[
    "@generated",
    "<auto-generated",
    "this file was automatically generated",
    "this file is automatically generated",
    "this file was auto-generated",
    "this file is auto-generated",
    "this file was autogenerated",
    "this file is autogenerated",
    "this file was generated by",
    "this file is generated by",
    "this file has been generated",
    "automatically generated by",
    "autogenerated by",
    "auto-generated by",
    "auto generated by",
    "generated by the protocol buffer compiler",
    "generated by protoc",
    "protoc-gen-",
    "generated by sqlc",
    "generated by buf",
    "swagger code generator",
    "swagger-codegen",
    "openapi generator",
    "openapi-generator",
    "generated by the grpc",
    "grpc-gateway",
    "flatbuffers compiler",
    "generated by flatc",
    "thrift compiler",
];

/// Phrases, lowercased, that turn a comment mentioning generation into a banner.
const WARNINGS: &[&str] = &["do not edit", "do not modify", "don't edit", "dont edit"];

/// Why the file at `path`, holding `text` (at least its first lines), looks
/// generated: its name or the banner comment line that says so. `None` when
/// nothing marks it as generated.
pub(crate) fn evidence(path: &Path, text: &str) -> Option<String> {
    by_name(path).or_else(|| by_banner(text))
}

/// Refuses a change to the file at `path`, shown as `shown` and holding `text`,
/// when it looks generated, unless `allowed` says the user asked for it.
///
/// `flag` names the argument that allows it, as the model would set it.
///
/// # Errors
///
/// Returns [`ToolError::Failed`] saying the file is generated, why, and what to
/// change instead.
pub(crate) fn refuse(
    path: &Path,
    shown: &str,
    text: &str,
    allowed: bool,
    flag: &str,
) -> Result<(), ToolError> {
    if allowed {
        return Ok(());
    }
    match evidence(path, text) {
        Some(why) => Err(ToolError::Failed(message(shown, &why, flag))),
        None => Ok(()),
    }
}

/// Refuses a change to the existing file at `path`, shown as `shown`, as
/// [`refuse`] does, reading only the top of the file.
///
/// # Errors
///
/// See [`refuse`]. A file that cannot be read is not refused; the change
/// reports that itself.
pub(crate) fn refuse_existing(
    path: &Path,
    shown: &str,
    allowed: bool,
    flag: &str,
) -> Result<(), ToolError> {
    if allowed || !path.is_file() {
        return Ok(());
    }
    refuse(path, shown, &head(path), allowed, flag)
}

/// The refusal for the file `shown`, generated as `why` says, telling the
/// model to set `flag` only when the user asked to change this file itself.
pub(crate) fn message(shown: &str, why: &str, flag: &str) -> String {
    format!(
        "{shown} is a generated file ({why}); a change made by hand is lost the next time it \
         is generated. Change the source it is generated from or the generator's \
         configuration and regenerate it instead; for a lockfile, change the manifest and let \
         the package manager update the lockfile. Only if the user explicitly asked you to \
         change this file itself, call again with {flag}."
    )
}

/// The first [`HEADER_BYTES`] bytes of the file at `path`, as text; empty
/// when it cannot be read.
fn head(path: &Path) -> String {
    let mut bytes = Vec::new();
    let _ =
        std::fs::File::open(path).and_then(|file| file.take(HEADER_BYTES).read_to_end(&mut bytes));
    String::from_utf8_lossy(&bytes).into_owned()
}

/// Why the name of `path` marks it as generated: a lockfile or a name
/// generators use.
fn by_name(path: &Path) -> Option<String> {
    let name = path.file_name()?.to_string_lossy();
    let lower = name.to_lowercase();
    if LOCKFILES.contains(&lower.as_str()) {
        return Some(format!(
            "{name} is a lockfile written by its package manager"
        ));
    }
    if let Some(suffix) = GENERATED_SUFFIXES
        .iter()
        .find(|suffix| lower.ends_with(*suffix))
    {
        return Some(format!(
            "its name matches *{suffix}, which code generators write"
        ));
    }
    GENERATED_PREFIXES
        .iter()
        .find(|prefix| lower.starts_with(*prefix))
        .map(|prefix| format!("its name matches {prefix}*, which code generators write"))
}

/// The comment line among the first [`HEADER_LINES`] lines of `text` that
/// says the file is generated, quoted with its line number.
fn by_banner(text: &str) -> Option<String> {
    let text = text.strip_prefix('\u{feff}').unwrap_or(text);
    let mut block: Option<&str> = None;
    for (index, line) in text.lines().take(HEADER_LINES).enumerate() {
        let trimmed = line.trim();
        let comment = match block {
            Some(close) => {
                if trimmed.contains(close) {
                    block = None;
                }
                true
            }
            None => {
                block = opens_block(trimmed);
                is_comment(trimmed)
            }
        };
        if comment && is_banner(&trimmed.to_lowercase()) {
            return Some(format!("line {}: {}", index + 1, quote(trimmed)));
        }
    }
    None
}

/// Whether `line`, trimmed, is a comment in one of the common comment syntaxes.
fn is_comment(line: &str) -> bool {
    [
        "//", "/*", "*", "#", "--", "<!--", ";", "%", "'", "{-", "(*", "rem ",
    ]
    .iter()
    .any(|start| line.starts_with(start))
}

/// The text that closes the block comment `line`, trimmed, opens and leaves
/// open, if it does.
fn opens_block(line: &str) -> Option<&'static str> {
    [("/*", "*/"), ("<!--", "-->"), ("{-", "-}"), ("(*", "*)")]
        .into_iter()
        .find(|(open, close)| line.starts_with(open) && !line[open.len()..].contains(close))
        .map(|(_, close)| close)
}

/// Whether the lowercased comment `line` is a banner of generated code: a
/// phrase only banners use, or the word generated next to a warning not to
/// edit.
fn is_banner(line: &str) -> bool {
    BANNERS.iter().any(|phrase| line.contains(phrase))
        || (line.contains("generated") && WARNINGS.iter().any(|warning| line.contains(warning)))
}

/// `line` in quotes, cut to [`QUOTE_CHARS`] characters.
fn quote(line: &str) -> String {
    match line.char_indices().nth(QUOTE_CHARS) {
        Some((end, _)) => format!("\"{}…\"", &line[..end]),
        None => format!("\"{line}\""),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The evidence for a file named `name` holding `text`.
    fn why(name: &str, text: &str) -> Option<String> {
        evidence(Path::new(name), text)
    }

    /// Banners of the common generators are found in comments near the top.
    #[test]
    fn finds_banners() {
        for (name, text) in [
            (
                "a.go",
                "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage a\n",
            ),
            (
                "b.go",
                "package b\n\n// Code generated by stringer; DO NOT EDIT.\n",
            ),
            (
                "c.py",
                "# -*- coding: utf-8 -*-\n# Generated by the protocol buffer compiler.  DO NOT EDIT!\n",
            ),
            ("d.rs", "// This file is @generated by prost-build.\n"),
            (
                "e.cs",
                "//------\n// <auto-generated>\n//     This code was generated by a tool.\n// </auto-generated>\n",
            ),
            (
                "f.ts",
                "/**\n * NOTE: This class is auto generated by OpenAPI Generator.\n */\n",
            ),
            (
                "g.java",
                "/**\n Autogenerated by Thrift Compiler (0.19.0)\n */\n",
            ),
            (
                "h.h",
                "// automatically generated by the FlatBuffers compiler, do not modify\n",
            ),
            ("i.sql", "-- Code generated by sqlc. DO NOT EDIT.\n"),
            (
                "j.html",
                "<!--\n  This file was automatically generated.\n-->\n",
            ),
        ] {
            assert!(why(name, text).is_some(), "{name}");
        }
        let quoted = why("a.go", "// Code generated by mockgen. DO NOT EDIT.\n").unwrap();
        assert_eq!(
            quoted,
            "line 1: \"// Code generated by mockgen. DO NOT EDIT.\""
        );
    }

    /// Lockfiles and the names generators use are known by name alone.
    #[test]
    fn knows_names() {
        for name in [
            "Cargo.lock",
            "web/package-lock.json",
            "yarn.lock",
            "pnpm-lock.yaml",
            "go.sum",
            "api/v1/service.pb.go",
            "proto/msg_pb2.py",
            "lib/model.g.dart",
            "Form1.Designer.cs",
            "zz_generated.deepcopy.go",
        ] {
            assert!(why(name, "").is_some(), "{name}");
        }
        assert!(why("Cargo.lock", "").unwrap().contains("lockfile"));
        assert!(why("x.pb.go", "").unwrap().contains("*.pb.go"));
    }

    /// Hand-written files are left alone: banners only count in comments near
    /// the top, and a mention of generation without a warning is not one.
    #[test]
    fn leaves_hand_written_files_alone() {
        assert_eq!(why("main.rs", "fn main() {}\n"), None);
        assert_eq!(
            why(
                "guard.rs",
                "const BANNER: &str = \"// Code generated DO NOT EDIT\";\n"
            ),
            None
        );
        assert_eq!(why("lib.rs", "// Parses the generated tokens.\n"), None);
        let late = format!(
            "{}// Code generated by x. DO NOT EDIT.\n",
            "fn f() {}\n".repeat(40)
        );
        assert_eq!(why("late.go", &late), None);
        assert_eq!(why("Cargo.toml", "[package]\n"), None);
    }

    /// The refusal names the evidence and the escape, and the escape lets the change through.
    #[test]
    fn refuses_unless_allowed() {
        let path = Path::new("x.pb.go");
        let refused = refuse(path, "x.pb.go", "", false, "generated: true").unwrap_err();
        let text = refused.to_string();
        assert!(text.contains("x.pb.go is a generated file"), "{text}");
        assert!(text.contains("*.pb.go"), "{text}");
        assert!(text.contains("generated: true"), "{text}");
        assert!(refuse(path, "x.pb.go", "", true, "generated: true").is_ok());
        assert!(
            refuse(
                Path::new("x.go"),
                "x.go",
                "package x\n",
                false,
                "generated: true"
            )
            .is_ok()
        );
    }
}
